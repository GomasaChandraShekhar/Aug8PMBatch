import { test, expect } from '@playwright/test';

test('test', async ({ page }) => {
    await page.getByRole('link', { name: 'HP', exact: true }).click();
    await page.getByRole('link', { name: 'HTC Touch HD' }).nth(3).click();
    await page.goto('https://ecommerce-playground.lambdatest.io/index.php?route=product/manufacturer/info&manufacturer_id=5');
    await expect(page.locator('#entry_212439')).toContainText('HTC Touch HD');
    await page.getByTitle('Add to Cart').nth(1).click();
    await page.getByRole('button', { name: 'Close' }).click();
    await page.getByRole('button', { name: '1' }).click();
    await page.getByRole('button', { name: ' Checkout' }).click();
    await expect(page.locator('#content')).toContainText('HTC Touch HD');
    await page.getByRole('link', { name: 'Checkout' }).click();
    await page.getByRole('link', { name: 'Checkout' }).click();
    await page.getByRole('button').filter({ hasText: /^$/ }).nth(1).click();
    await page.getByRole('link', { name: 'Continue' }).click();
    await page.getByRole('link', { name: 'Hard disk' }).click();
    await page.getByRole('link', { name: 'Headphones' }).click();
    await expect(page.locator('#entry_212408')).toContainText('Palm Treo Pro');
    await page.getByTitle('Add to Cart').nth(1).click();
    await page.getByRole('link', { name: 'View Cart ' }).click();
    await page.getByRole('button').filter({ hasText: /^$/ }).nth(1).click();
    await page.getByRole('link', { name: 'Desktop', exact: true }).click();
    await expect(page.locator('#entry_212408')).toContainText('iPod Nano');
    await page.locator('.btn.btn-cart.cart-36').click();
    await page.getByRole('link', { name: 'View Cart ' }).click();
    await page.locator('input[name="quantity[226191]"]').click();
    await page.locator('input[name="quantity[226191]"]').fill('2');
    await page.getByRole('heading', { name: 'Shopping Cart  (0.00kg)' }).click();
    await page.getByRole('link', { name: 'Checkout' }).click();
    await page.getByRole('link', { name: 'Bluetooth Speaker' }).click();
    await page.locator('#mz-filter-panel-0-5').getByText('In stock', { exact: true }).click();
    await expect(page.locator('#entry_212408')).toContainText('Apple Cinema 30"');
    await page.getByTitle('Add to Cart').nth(1).click();
    await page.getByRole('button', { name: 'Decrease quantity' }).click();
    await page.getByRole('button', { name: 'Add to Cart' }).click();
    await page.getByRole('button', { name: 'Increase quantity' }).click();
    await page.locator('.icon.btn').click();
    await page.getByText('Product Compare (1) ×').click();
    await page.getByRole('button', { name: 'Close' }).click();
});